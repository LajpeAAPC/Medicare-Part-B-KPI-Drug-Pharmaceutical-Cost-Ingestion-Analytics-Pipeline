-- ------------------------------------------------------------------------------
-- QUERY 1: TOP 10 HIGH-VOLUME DRUGS BY TOTAL MEDICARE PAYOUT
-- Focus: Identifies the core financial drivers and average costs per drug class.
-- Truncation Control: Uses CAST to BIGINT to handle massive service counts.
-- ------------------------------------------------------------------------------
SELECT 
    hcpcs,
    description,
    SUM(CAST(allowed_services AS BIGINT)) AS total_services_delivered,
    SUM(payment) AS total_medicare_payout,
    ROUND(AVG(allowed_charges), 2) AS average_allowed_charge
FROM j_code_drugs_2024
GROUP BY hcpcs, description
ORDER BY total_medicare_payout DESC
LIMIT 10;


-- ------------------------------------------------------------------------------
-- QUERY 2: CONDITIONAL UTILITY LOGIC (CASE WHEN)
-- Focus: Categorizes drug rows into corporate utilization tiers.
-- Scale Design: Upper bounds set to millions to mirror multi-billion dollar scale.
-- ------------------------------------------------------------------------------
