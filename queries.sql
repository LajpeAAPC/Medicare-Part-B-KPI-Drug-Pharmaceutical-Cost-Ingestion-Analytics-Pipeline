    hcpcs,
    description,
    allowed_services,
    CASE 
        WHEN allowed_services >= 10000000 THEN 'Ultra-High Mass Distribution'
        WHEN allowed_services >= 1000000  THEN 'High Mass Distribution'
        WHEN allowed_services >= 100000   THEN 'Moderate Distribution'
        ELSE 'Specialty / Niche Distribution'
    END AS volume_tier
FROM j_code_drugs_2024;


